import Foundation
import GRDB

// MARK: - Speaker

struct Speaker: Identifiable, Codable, FetchableRecord, PersistableRecord {
    var id: String
    var nameEn: String
    var nickname: String?
    var nameRu: String?
    var isMe: Bool
    var isConfirmed: Bool
    var createdAt: Date
    var embedding: Data?
    /// Persistent color hue (0..<360) shown across transcript, waveform and
    /// speaker views. nil only for rows created by
    /// code paths that bypass findOrCreateSpeaker — display falls back to djb2.
    var hue: Double?

    static let databaseTableName = "speakers"

    enum Columns {
        static let id = Column(CodingKeys.id)
        static let nameEn = Column(CodingKeys.nameEn)
        static let isMe = Column(CodingKeys.isMe)
        static let isConfirmed = Column(CodingKeys.isConfirmed)
        static let embedding = Column(CodingKeys.embedding)
    }

    /// True when `name` is an auto-generated diarization label (e.g. "speaker_1").
    /// The single place that knows the `speaker_N` shape (speaker-row-per-mint).
    static func isAutoLabel(_ name: String) -> Bool {
        name.range(of: #"^speaker_\d+$"#, options: .regularExpression) != nil
    }

    /// How a label reads in the window: `speaker_3` → "Speaker 3", a name as it
    /// is. The CLI, JSON and MCP keep the raw label.
    static func windowLabel(_ label: String) -> String {
        isAutoLabel(label) ? "Speaker " + label.dropFirst("speaker_".count) : label
    }

    /// True when the speaker name is an auto-generated diarization label.
    var isAutoGenerated: Bool {
        Self.isAutoLabel(nameEn)
    }

    /// Composed display name: nameRu ?? nickname ?? nameEn
    var displayName: String {
        if let ru = nameRu, !ru.isEmpty { return ru }
        if let nick = nickname, !nick.isEmpty { return nick }
        return nameEn
    }

    init(
        id: String = UUID().uuidString,
        nameEn: String,
        nickname: String? = nil,
        nameRu: String? = nil,
        isMe: Bool = false,
        isConfirmed: Bool = false,
        createdAt: Date = Date(),
        embedding: Data? = nil,
        hue: Double? = nil
    ) {
        self.id = id
        self.nameEn = nameEn
        self.nickname = nickname
        self.nameRu = nameRu
        self.isMe = isMe
        self.isConfirmed = isConfirmed
        self.createdAt = createdAt
        self.embedding = embedding
        self.hue = hue
    }
}

/// Which embedder produced a vector (dual-pool transition). Both spaces
/// are 256-dim, so the space is tracked structurally — `speakers.embedding` +
/// `speakers.embeddingV2` columns, `meetings.diarizer` marker — never inferred
/// from the data.
enum EmbeddingSpace: String, Sendable, CaseIterable {
    /// Online FluidAudio `DiarizerManager` embedder — the legacy enrolled pool.
    case v1 = "embedding"
    /// WeSpeaker via `OfflineDiarizerManager` (pyannote stack).
    case v2 = "embeddingV2"

    /// Matching `meetings.diarizer` filter: which meetings' segment embeddings
    /// live in this space. Legacy rows (NULL) predate the offline diarizer.
    var meetingFilterSQL: String {
        switch self {
        case .v1: "COALESCE(m.diarizer, 'online') <> 'offline'"
        case .v2: "m.diarizer = 'offline'"
        }
    }
}

extension Speaker {
    static func encodeEmbedding(_ embedding: [Float]) -> Data {
        embedding.withUnsafeBytes { Data($0) }
    }

    static func decodeEmbedding(_ data: Data) -> [Float] {
        data.withUnsafeBytes { Array($0.bindMemory(to: Float.self)) }
    }

    var embeddingArray: [Float]? {
        embedding.map { Self.decodeEmbedding($0) }
    }

    /// Pool hygiene: an auto-minted `speaker_N` the user has not
    /// named yet never enters the voice-matching pool. Its canonical is built
    /// from whatever junk minted it and acts as a high-similarity magnet — the
    /// an audit saw echo match an old echo canonical at 0.944. Naming the
    /// person restores membership.
    ///
    /// This is the guard that lets minting stay on for the mic track
    /// (`foreign-voices-on-mic`, решение 2): a fresh unconfirmed persona cannot
    /// influence the next meeting's recognition.
    var isEligibleForMatchingPool: Bool {
        guard embeddingArray != nil else { return false }
        let isPhantom = !isConfirmed && Self.isAutoLabel(displayName)
        return !isPhantom
    }
}

