import SwiftUI

struct SpeakerRenamePopover: View {
    let currentLabel: String
    /// Rename all segments with this label. (displayName, speakerId?) — speakerId is set when picking from the list.
    let onRename: (String, String?) -> Void
    let onDismiss: () -> Void
    // Per-segment reassignment (nil = don't show reassign UI)
    var onReassign: ((String, String) -> Void)? // (speakerId, speakerName)
    var onReassignNew: ((String) -> Void)?
    var onMarkAsMe: (() -> Void)?

    @State private var nameInput = ""
    @State private var allSpeakers: [Speaker] = []
    @State private var isReassignMode = false
    private let speakerRepo = SpeakerRepository()

    var filteredSpeakers: [Speaker] {
        let speakers = allSpeakers.filter { $0.nameEn != currentLabel && !$0.isAutoGenerated }
        if nameInput.isEmpty { return speakers }
        return speakers.filter {
            $0.nameEn.localizedCaseInsensitiveContains(nameInput) ||
            $0.displayName.localizedCaseInsensitiveContains(nameInput) ||
            $0.nickname?.localizedCaseInsensitiveContains(nameInput) == true
        }
    }

    var body: some View {
        VStack(alignment: .leading, spacing: VedivoxSpace.m) {
            // Mode toggle (only if reassign callbacks are provided)
            if onReassign != nil {
                Picker("", selection: $isReassignMode) {
                    Text("Rename all").tag(false)
                    Text("This segment").tag(true)
                }
                .pickerStyle(.segmented)
                .labelsHidden()
            }

            if let onMarkAsMe {
                Button {
                    onMarkAsMe()
                } label: {
                    Label("Mark as me", systemImage: "person.circle.fill")
                        .frame(maxWidth: .infinity)
                }
                .buttonStyle(.vedivoxProminent)
            }

            Text(isReassignMode ? "Reassign to:" : "Rename \(currentLabel)")
                .vedivoxFont(.overline)
                .foregroundStyle(Color.Vedivox.fgSecondary)

            TextField("Speaker name", text: $nameInput)
                .vedivoxField()
                .onSubmit {
                    let name = nameInput.trimmingCharacters(in: .whitespacesAndNewlines)
                    guard !name.isEmpty else { return }
                    if isReassignMode {
                        onReassignNew?(name)
                    } else {
                        onRename(name, nil)
                    }
                }

            if !filteredSpeakers.isEmpty {
                ScrollView {
                    LazyVStack(alignment: .leading, spacing: VedivoxSpace.xxs) {
                        ForEach(filteredSpeakers) { speaker in
                            Button {
                                if isReassignMode {
                                    onReassign?(speaker.id, speaker.displayName)
                                } else {
                                    onRename(speaker.displayName, speaker.id)
                                }
                            } label: {
                                HStack {
                                    VStack(alignment: .leading, spacing: VedivoxSpace.xxs) {
                                        Text(speaker.displayName)
                                            .vedivoxFont(.row)
                                        if let nick = speaker.nickname, !nick.isEmpty, nick != speaker.displayName {
                                            Text("@\(nick)")
                                                .vedivoxFont(.caption)
                                                .foregroundStyle(Color.Vedivox.fgSecondary)
                                        }
                                    }
                                    if speaker.isMe {
                                        Text("(me)")
                                            .vedivoxFont(.caption)
                                            .foregroundStyle(Color.Vedivox.fgSecondary)
                                    }
                                    Spacer()
                                }
                                .contentShape(Rectangle())
                                .padding(.horizontal, VedivoxSpace.s)
                                .padding(.vertical, VedivoxSpace.xs)
                            }
                            .buttonStyle(.plain)
                        }
                    }
                }
                .frame(maxHeight: 150)
            }
        }
        .padding(VedivoxSpace.l)
        .frame(width: 220, height: 250)
        .task {
            allSpeakers = (try? await speakerRepo.all()) ?? []
        }
    }
}
