import SwiftUI

struct SelectionActionBar: View {
    let selectedCount: Int
    let meSpeaker: Speaker?
    let onReassign: (String, String) -> Void // (speakerId, speakerName)
    let onReassignNew: (String) -> Void
    let onMarkAsMe: () -> Void
    /// «Не в транскрипт» / «Вернуть» for the selection (transcript-exclusion-marks).
    let onExclude: () -> Void
    let onInclude: () -> Void
    let onClear: () -> Void

    @State private var showReassignPopover = false
    @State private var nameInput = ""
    @State private var allSpeakers: [Speaker] = []
    private let speakerRepo = SpeakerRepository()

    private var filteredSpeakers: [Speaker] {
        let speakers = allSpeakers.filter { !$0.isAutoGenerated }
        if nameInput.isEmpty { return speakers }
        return speakers.filter {
            $0.nameEn.localizedCaseInsensitiveContains(nameInput) ||
            $0.displayName.localizedCaseInsensitiveContains(nameInput) ||
            $0.nickname?.localizedCaseInsensitiveContains(nameInput) == true
        }
    }

    var body: some View {
        HStack(spacing: VedivoxSpace.l) {
            Text("\(selectedCount) selected")
                .vedivoxFont(.bodyStrong)
                .foregroundStyle(Color.Vedivox.fgSecondary)

            Button {
                showReassignPopover = true
            } label: {
                Label("Reassign to...", systemImage: "person.2")
            }
            .popover(isPresented: $showReassignPopover) {
                reassignPopover
            }

            if meSpeaker != nil {
                Button {
                    onMarkAsMe()
                } label: {
                    Label("Mark as me", systemImage: "person.circle.fill")
                }
                .buttonStyle(.vedivoxProminent)
            }

            Button {
                onExclude()
            } label: {
                Label("Exclude", systemImage: "eye.slash")
            }
            .help("Hide the selected segments from the transcript, search and export (reversible)")

            Button {
                onInclude()
            } label: {
                Label("Restore", systemImage: "eye")
            }
            .help("Bring the selected segments back into the transcript")

            Spacer()

            Button {
                onClear()
            } label: {
                Image(systemName: "xmark.circle.fill")
                    .foregroundStyle(Color.Vedivox.fgSecondary)
            }
            .buttonStyle(.plain)
            .help("Clear selection")
        }
        .padding(.horizontal)
        .padding(.vertical, VedivoxSpace.s)
        .background(Color.Vedivox.bgSidebar)
    }

    private var reassignPopover: some View {
        VStack(alignment: .leading, spacing: VedivoxSpace.m) {
            Text("Reassign \(selectedCount) segments to:")
                .vedivoxFont(.overline)
                .foregroundStyle(Color.Vedivox.fgSecondary)

            TextField("Speaker name", text: $nameInput)
                .vedivoxField()
                .onSubmit {
                    let name = nameInput.trimmingCharacters(in: .whitespacesAndNewlines)
                    guard !name.isEmpty else { return }
                    showReassignPopover = false
                    onReassignNew(name)
                }

            if !filteredSpeakers.isEmpty {
                ScrollView {
                    LazyVStack(alignment: .leading, spacing: VedivoxSpace.xxs) {
                        ForEach(filteredSpeakers) { speaker in
                            Button {
                                showReassignPopover = false
                                onReassign(speaker.id, speaker.displayName)
                            } label: {
                                HStack {
                                    VStack(alignment: .leading, spacing: VedivoxSpace.xxs) {
                                        Text(speaker.displayName)
                                            .vedivoxFont(.row)
                                        if let nick = speaker.nickname, !nick.isEmpty, nick != speaker.displayName {
                                            Text("@\(nick)")
                                                .vedivoxFont(.caption)
                                                .foregroundStyle(Color.Vedivox.fgSecondary)
                                        }
                                    }
                                    if speaker.isMe {
                                        Text("(me)")
                                            .vedivoxFont(.caption)
                                            .foregroundStyle(Color.Vedivox.fgSecondary)
                                    }
                                    Spacer()
                                }
                                .contentShape(Rectangle())
                                .padding(.horizontal, VedivoxSpace.s)
                                .padding(.vertical, VedivoxSpace.xs)
                            }
                            .buttonStyle(.plain)
                        }
                    }
                }
                .frame(maxHeight: 150)
            }
        }
        .padding(VedivoxSpace.l)
        .frame(width: 240, height: 250)
        .task {
            allSpeakers = (try? await speakerRepo.all()) ?? []
        }
    }
}
